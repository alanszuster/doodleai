"""Which build is running: the app version and the model it serves.

``VERSION`` (repo root) is generated by the deploy workflow with the release version and is not
in git; without it the build reports ``dev``. The model comes from ``model_card.json`` next to
the model file.
"""

from __future__ import annotations

import functools
import json
import os

from classifier import ARTIFACTS_DIR, ROOT_DIR

VERSION_PATH = os.path.join(ROOT_DIR, "VERSION")
CARD_PATH = os.path.join(ARTIFACTS_DIR, "model_card.json")


def _read_version() -> str:
    try:
        with open(VERSION_PATH, encoding="utf-8") as handle:
            return handle.read().strip() or "dev"
    except OSError:
        return "dev"


__version__ = _read_version()


def app_info() -> dict:
    return {"version": __version__}


@functools.cache
def model_info() -> dict | None:
    """Identity of the served model, or None when it has no card (e.g. a hand-placed model)."""
    try:
        with open(CARD_PATH, encoding="utf-8") as handle:
            card = json.load(handle)
    except (OSError, ValueError):
        return None
    return {
        "run_id": card.get("run_id"),
        "top1": card.get("metrics", {}).get("top1"),
        "sha256": card.get("model_sha256"),
    }
